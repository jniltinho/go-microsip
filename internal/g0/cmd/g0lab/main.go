// g0lab runs the G0 spike probes (package g0) against the disposable Asterisk lab and prints a JSON
// report. It takes no account settings from the user: only the lab's fixture directory.
//
//	g0lab [-lab /lab] [-server pbx] [-run prefix] [-out report.json] [-debug]
package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"log/slog"
	"os"
	"os/signal"
	"strings"
	"syscall"

	"github.com/emiago/sipgo/sip"

	"github.com/jniltinho/go-microsip/internal/g0"
)

func main() {
	dir := flag.String("lab", "/lab", "fixture directory generated by docker/asterisk/lab.py")
	server := flag.String("server", "pbx", "host name of the lab PBX")
	only := flag.String("run", "", "run only the scenarios whose name starts with this prefix")
	debug := flag.Bool("debug", false, "log SIP library diagnostics")
	out := flag.String("out", "", "also write the JSON report to this file")
	flag.Parse()

	level := slog.LevelInfo
	if *debug {
		level = slog.LevelDebug
		sip.SIPDebug = true // message traces carry digests and lab passwords' hashes only
	}
	log := slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: level}))
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	lab, err := g0.LoadLab(*dir, *server, log)
	if err != nil {
		fmt.Fprintln(os.Stderr, "g0lab:", err)
		os.Exit(2)
	}
	var list []g0.Scenario
	for _, s := range g0.Scenarios() {
		if strings.HasPrefix(s.Name, *only) {
			list = append(list, s)
		}
	}
	results := lab.Run(ctx, list)
	failed := 0
	for _, r := range results {
		if !r.OK {
			failed++
		}
	}
	report := map[string]any{"scenarios": len(results), "failed": failed, "results": results}
	text, _ := json.MarshalIndent(report, "", "  ")
	fmt.Println(string(text))
	if *out != "" {
		if err := os.WriteFile(*out, append(text, '\n'), 0o600); err != nil {
			fmt.Fprintln(os.Stderr, "g0lab:", err)
			os.Exit(2)
		}
	}
	if failed > 0 || len(results) == 0 {
		os.Exit(1)
	}
}
